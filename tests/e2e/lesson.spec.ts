import { test, expect } from '@playwright/test';
test('comenzar, registrar, pausar, recargar, reanudar y finalizar sin duplicados', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Comenzar clase' }).click();
  await expect(page.getByRole('heading', { name: 'Tu punto de partida con el acordeón' })).toBeVisible();
  await page.getByLabel('Necesita repetir', { exact: true }).check();
  await page.getByLabel('Observación (opcional)').fill('Sin experiencia');
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tu clase está en pausa.' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Continuar clase' }).click();
  await expect(page.getByRole('heading', { name: 'Escucha un cambio que ya conoces' })).toBeVisible();
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await page.getByRole('button', { name: 'Reanudar', exact: true }).click();
  await page.getByLabel('Conseguido', { exact: true }).check();
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
  await page.getByLabel('Omitido', { exact: true }).check();
  await expect(page.getByRole('button', { name: 'Finalizar clase' })).toBeDisabled();
  await page.getByLabel('Motivo de la omisión').fill('Molestia en la garganta');
  await page.getByRole('button', { name: 'Finalizar clase' }).click();
  await expect(page.getByText('CLASE GUARDADA', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Progreso', exact: true }).click();
  await expect(page.locator('.history')).toHaveCount(1);
  await expect(page.getByText('Acordeón: necesita repetir', { exact: true })).toBeVisible();
  await expect(page.getByText('Canto: omitido', { exact: true })).toBeVisible();
});
test('permite escribir observaciones mientras el reloj avanza', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Comenzar clase' }).click();
  const field = page.getByLabel('Observación (opcional)');
  await field.focus();
  await page.waitForTimeout(1200);
  await expect(field).toBeFocused();
  await field.fill('Mi referencia');
  await expect(field).toHaveValue('Mi referencia');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('guarda el perfil y rechaza una copia inválida sin alterar datos', async ({ page }) => {
  await page.goto('/');
  await page.getByText('Mi perfil y ajustes', { exact: true }).click();
  await page.getByLabel('Edad', { exact: true }).fill('48');
  await page.getByRole('button', { name: 'Guardar perfil' }).click();
  await expect(page.getByRole('status')).toHaveText('Perfil guardado.');
  await page.reload();
  await page.getByText('Mi perfil y ajustes', { exact: true }).click();
  await expect(page.getByLabel('Edad', { exact: true })).toHaveValue('48');
  await page.getByRole('button', { name: 'Progreso', exact: true }).click();
  await page.getByText('Exportar o importar un registro', { exact: true }).click();
  await page.getByLabel('Seleccionar copia JSON').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":2}') });
  await expect(page.getByRole('alert')).toContainText('Copia no válida');
  await expect(page.locator('.history')).toHaveCount(0);
});
